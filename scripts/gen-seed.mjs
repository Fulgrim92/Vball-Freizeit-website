// Writes supabase/seed.sql from the season data the demo uses (src/data/season.ts), so the
// database starts with the same leagues, teams and fixtures as the mock site.
//
//   node scripts/gen-seed.mjs                  fixtures only, no results
//   node scripts/gen-seed.mjs --demo-results   also the simulated results of games before today
//   --out <file>                               write somewhere else than supabase/seed.sql
import { build } from 'esbuild'
import { writeFileSync, mkdtempSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

process.env.TZ = 'Europe/Berlin'
const withResults = process.argv.includes('--demo-results')
const target = process.argv.includes('--out') ? process.argv[process.argv.indexOf('--out') + 1] : 'supabase/seed.sql'

const dir = mkdtempSync(join(tmpdir(), 'vfm-seed-'))
const out = join(dir, 'season.mjs')
await build({ entryPoints: ['src/data/season.ts'], bundle: true, format: 'esm', platform: 'node', outfile: out, logLevel: 'error' })
const { LEAGUES, TEAMS, MATCHES, PENDING_RESULT_ID } = await import(out)
rmSync(dir, { recursive: true })

const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`)
const arr = (a) => `array[${a.map(q).join(', ')}]::text[]`
const json = (v) => `${q(JSON.stringify(v))}::jsonb`
const rows = (list) => list.map((r) => `  (${r.join(', ')})`).join(',\n')

const sql = `-- Generated by scripts/gen-seed.mjs from src/data/season.ts. Do not edit by hand.
-- ${LEAGUES.length} leagues, ${TEAMS.length} teams, ${MATCHES.length} games${withResults ? ', with simulated results' : ''}.

insert into public.leagues (id, tier, label, lead, sort) values
${rows(LEAGUES.map((l, i) => [q(l.id), l.tier, q(l.label), q(l.lead), i]))}
on conflict (id) do update set tier = excluded.tier, label = excluded.label, lead = excluded.lead, sort = excluded.sort;

insert into public.teams (id, league_id, name, short, club, hue, venues, slots, contacts) values
${rows(TEAMS.map((t) => [q(t.id), q(t.league), q(t.name), q(t.short), q(t.club), t.hue, arr(t.venues), json(t.slots), arr(t.contacts)]))}
on conflict (id) do update set league_id = excluded.league_id, name = excluded.name, short = excluded.short, club = excluded.club,
  hue = excluded.hue, venues = excluded.venues, slots = excluded.slots, contacts = excluded.contacts;

insert into public.matches (id, no, league_id, home_id, away_id, date, time, venue, sets) values
${rows(MATCHES.map((m) => [q(m.id), m.no, q(m.league), q(m.home), q(m.away), q(m.date), q(m.time), q(m.venue), withResults && m.sets && m.id !== PENDING_RESULT_ID ? json(m.sets) : 'null']))}
on conflict (id) do update set no = excluded.no, league_id = excluded.league_id, home_id = excluded.home_id, away_id = excluded.away_id,
  date = excluded.date, time = excluded.time, venue = excluded.venue;
`

writeFileSync(target, sql)
console.log(`${target}: ${LEAGUES.length} leagues, ${TEAMS.length} teams, ${MATCHES.length} games`)
